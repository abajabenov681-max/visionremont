#!/usr/bin/env python3
"""Генерирует PDF-структуру RepairLink для объяснения жюри (без tech-жаргона)."""

from pathlib import Path
from fpdf import FPDF

FONT = "/System/Library/Fonts/Supplemental/Arial Unicode.ttf"
OUT = Path(__file__).resolve().parents[1] / "docs" / "RepairLink-структура-для-жюри.pdf"


class JuryPDF(FPDF):
    def header(self):
        if self.page_no() == 1:
            return
        self.set_font("ArialUni", size=9)
        self.set_text_color(120, 120, 120)
        self.cell(0, 8, "RepairLink - структура продукта для жюри", align="R")
        self.ln(10)

    def footer(self):
        self.set_y(-15)
        self.set_font("ArialUni", size=9)
        self.set_text_color(140, 140, 140)
        self.cell(0, 10, f"{self.page_no()}", align="C")

    def _text(self, h, text, fill=False):
        self.set_x(self.l_margin)
        self.multi_cell(0, h, text, fill=fill, new_x="LMARGIN", new_y="NEXT")

    def h2(self, text):
        self.ln(3)
        self.set_font("ArialUni", size=13)
        self.set_text_color(245, 98, 12)
        self._text(8, text)
        self.ln(1)

    def h3(self, text):
        self.ln(2)
        self.set_font("ArialUni", size=11)
        self.set_text_color(40, 40, 40)
        self._text(7, text)
        self.ln(1)

    def body(self, text):
        self.set_font("ArialUni", size=11)
        self.set_text_color(35, 35, 35)
        self._text(6.5, text)
        self.ln(1)

    def bullet(self, text):
        self.set_font("ArialUni", size=11)
        self.set_text_color(35, 35, 35)
        self.set_x(self.l_margin + 4)
        self.multi_cell(0, 6.5, f"-  {text}", new_x="LMARGIN", new_y="NEXT")
        self.ln(0.5)

    def note(self, text):
        self.set_fill_color(245, 245, 245)
        self.set_font("ArialUni", size=10)
        self.set_text_color(60, 60, 60)
        self._text(6, text, fill=True)
        self.ln(3)


def build():
    OUT.parent.mkdir(parents=True, exist_ok=True)
    pdf = JuryPDF(format="A4")
    pdf.set_margins(18, 16, 18)
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.add_font("ArialUni", "", FONT)
    pdf.add_page()

    # Title
    pdf.set_font("ArialUni", size=22)
    pdf.set_text_color(245, 98, 12)
    pdf._text(12, "RepairLink")
    pdf.set_font("ArialUni", size=14)
    pdf.set_text_color(20, 20, 20)
    pdf._text(8, "Структура продукта - шпаргалка для жюри")
    pdf.ln(2)
    pdf.body(
        "Этот документ объясняет, как устроен RepairLink простыми словами. "
        "Его можно использовать на защите: что есть в продукте, как работает сделка "
        "и где лежат ключевые части системы."
    )
    pdf.note(
        "Главная идея продукта: вызвать мастера как такси — с фиксированной ценой, "
        "безопасной оплатой и цифровой гарантией после работы."
    )

    # 1. What is the product
    pdf.h2("1. Что такое RepairLink")
    pdf.body(
        "Платформа бытового ремонта. Клиент создаёт заявку, мастер принимает её, "
        "выполняет работу, клиент подтверждает результат. После этого:"
    )
    pdf.bullet("деньги переводятся мастеру (с комиссией платформы 7%);")
    pdf.bullet("автоматически создаётся цифровая гарантия с фото до/после;")
    pdf.bullet("работа сохраняется в «Паспорте ремонта» квартиры.")
    pdf.body(
        "Специализации: Сантехник, Ремонтник, Плиточник, Мебельщик."
    )

    # 2. Three roles
    pdf.h2("2. Три роли пользователей")
    pdf.h3("Клиент")
    pdf.bullet("создаёт обычный заказ или аварийный вызов;")
    pdf.bullet("выбирает мастера из откликов;")
    pdf.bullet("подтверждает работу и получает гарантию;")
    pdf.bullet("смотрит историю ремонта по адресу (паспорт).")
    pdf.h3("Мастер")
    pdf.bullet("включает режим «На линии» для срочных вызовов;")
    pdf.bullet("откликается на заказы или принимает аварийные;")
    pdf.bullet("загружает фото результата;")
    pdf.bullet("видит Trust Score и статус проверки документов.")
    pdf.h3("Администратор")
    pdf.bullet("проверяет документы мастеров (подтвердить / отклонить);")
    pdf.bullet("смотрит пользователей, заказы, отзывы;")
    pdf.bullet("это ручная модерация — как заявлено в TVEP.")

    # 3. Main scenarios
    pdf.h2("3. Главные сценарии (что показывать на демо)")
    pdf.h3("А. Аварийный вызов")
    pdf.body(
        "Клиент нажимает «Аварийный вызов» → заявка уходит онлайн-мастерам этой "
        "специализации в реальном времени → первый нажавший «Принять» получает заказ. "
        "Остальным карточка пропадает. Это и есть «как такси»."
    )
    pdf.h3("Б. Обычный заказ")
    pdf.body(
        "Клиент создаёт заказ с бюджетом → мастера оставляют отклики с ценой → "
        "клиент выбирает одного → средства резервируются → работа выполняется → "
        "клиент подтверждает → гарантия и выплата."
    )
    pdf.h3("В. Безопасная сделка (эскроу)")
    pdf.body(
        "При выборе мастера: «Средства зарезервированы». "
        "После подтверждения работы клиентом: «Переведено мастеру». "
        "На экране видно формулу: комиссия платформы = 7% от суммы, "
        "мастеру уходит остаток. Комиссия удерживается только после подтверждения."
    )
    pdf.note(
        "Важно для Q&A: реальный банковский платёж (Kaspi Pay и т.п.) пока не подключён - "
        "нужна бизнес-верификация. Модуль эскроу в коде уже отдельный и готов к подключению провайдера."
    )
    pdf.h3("Г. Паспорт ремонта")
    pdf.body(
        "Все завершённые работы группируются по адресу квартиры. "
        "Это долгосрочная история ремонта: дата, мастер, фото, гарантия. "
        "Можно скачать как PDF. Это product moat - «память» о ремонте квартиры."
    )

    # 4. How the system is organized
    pdf.h2("4. Как устроена система (просто)")
    pdf.body(
        "Представьте три этажа здания:"
    )
    pdf.h3("Этаж 1 — Экраны (то, что видит пользователь)")
    pdf.bullet("зона клиента: главная, заказы, гарантии, паспорт, профиль;")
    pdf.bullet("зона мастера: «на линии», лента заказов, рейтинг, документы;")
    pdf.bullet("зона админа: дашборд, проверка документов, пользователи.")
    pdf.h3("Этаж 2 — Правила бизнеса (мозг продукта)")
    pdf.body(
        "Здесь живут отдельные модули — каждый отвечает за свою задачу. "
        "Так проще объяснять и развивать продукт:"
    )
    pdf.bullet("Авторизация — вход по SMS-коду;")
    pdf.bullet("Заказы — создание, отклики, выбор мастера;")
    pdf.bullet("Мэтчинг — аварийный вызов в реальном времени;")
    pdf.bullet("Эскроу — резерв и выплата денег;")
    pdf.bullet("Гарантии — сертификат после подтверждения;")
    pdf.bullet("Паспорт ремонта — история по адресу;")
    pdf.bullet("Админ — проверка документов и модерация.")
    pdf.h3("Этаж 3 — Хранилище данных")
    pdf.body(
        "Всё хранится в облачной базе (Supabase): пользователи, заказы, фото, "
        "гарантии, коды SMS, сделки эскроу. Есть правила доступа — "
        "клиент не видит чужие данные, мастер — только свои заказы."
    )

    # 5. What is in the folders (simple map)
    pdf.add_page()
    pdf.h2("5. Карта папок проекта (что где лежит)")
    pdf.body("Не нужно читать код — достаточно понимать назначение разделов.")
    pdf.h3("src/app — экраны сайта")
    pdf.bullet("(client) — кабинет клиента;")
    pdf.bullet("(master) — кабинет мастера;")
    pdf.bullet("(admin) — админ-панель;")
    pdf.bullet("api — «двери», через которые экран просит сервер что-то сделать;")
    pdf.bullet("login — вход по телефону.")
    pdf.h3("src/features — готовые блоки экранов")
    pdf.bullet("matching — аварийный вызов и поиск мастера;")
    pdf.bullet("orders — формы заказа и откликов;")
    pdf.bullet("escrow — плашка «средства зарезервированы / переведено»;")
    pdf.bullet("chat, reviews, warranties, profile — чат, отзывы, гарантии, профиль.")
    pdf.h3("src/services — бизнес-правила")
    pdf.body(
        "Именно здесь логика продукта: нельзя подтвердить чужой заказ, "
        "нельзя принять уже взятый срочный вызов, после подтверждения "
        "создаётся гарантия и запускается выплата."
    )
    pdf.h3("src/repositories — работа с базой")
    pdf.body(
        "Единственное место, где код напрямую читает и пишет в таблицы. "
        "Сервисы не лезут в базу сами — просят repository."
    )
    pdf.h3("supabase/")
    pdf.bullet("migrations — схема базы (таблицы, правила, функции);")
    pdf.bullet("functions — облачные функции SMS OTP (отправка и проверка кода).")

    # 6. Auth
    pdf.h2("6. Вход в систему")
    pdf.body(
        "Пользователь вводит телефон → получает SMS-код (4 цифры, действует 5 минут) → "
        "вводит код → входит. Не больше 3 попыток и не чаще 1 отправки в минуту."
    )
    pdf.note(
        "На демо/финале можно использовать код 1234 без реальной SMS - "
        "это страховка на случай плохой сети в зале. Логика входа та же."
    )

    # 7. Trust score & docs
    pdf.h2("7. Trust Score и документы мастера")
    pdf.body(
        "Trust Score — показатель доверия к мастеру. В него входят рейтинг, "
        "число завершённых заказов и подтверждённые документы."
    )
    pdf.bullet("мастер загружает документ → статус «На проверке»;")
    pdf.bullet("админ подтверждает или отклоняет;")
    pdf.bullet("после подтверждения Trust Score пересчитывается.")
    pdf.body(
        "Это не автоматическая проверка через гос. API, а обязательная "
        "ручная модерация администратором - как написано в TVEP."
    )

    # 8. Data that matters
    pdf.h2("8. Что хранится в системе (главные сущности)")
    pdf.bullet("Пользователи и профили (клиент / мастер);")
    pdf.bullet("Специализации и связь «мастер умеет X»;")
    pdf.bullet("Заказы, фото до/после, отклики;")
    pdf.bullet("Чат по заказу;")
    pdf.bullet("Гарантии и сертификаты;")
    pdf.bullet("Сделки эскроу (резерв / выплата);")
    pdf.bullet("SMS-коды;")
    pdf.bullet("Журнал действий админа.")

    # 9. Q&A cheat sheet
    pdf.h2("9. Шпаргалка для вопросов жюри")
    pdf.h3("«Как вы матчите мастера?»")
    pdf.body(
        "Срочные заявки уходят онлайн-мастерам нужной специализации через realtime-канал. "
        "Побеждает первый принявший - атомарно, без двойного назначения."
    )
    pdf.h3("«Где деньги?»")
    pdf.body(
        "Эскроу-модуль резервирует и распределяет сумму по формуле 7%. "
        "Платёжный провайдер - следующий шаг после бизнес-верификации; "
        "архитектура уже отделена под это."
    )
    pdf.h3("«Чем вы отличаетесь?»")
    pdf.body(
        "Не только вызвать мастера, но и довести сделку до конца: "
        "фиксированная цена, безопасная оплата, цифровая гарантия и паспорт ремонта квартиры."
    )
    pdf.h3("«Есть ли ИИ?»")
    pdf.body(
        "Нет. В TVEP ИИ не заявлен. Фокус — мэтчинг, эскроу, гарантия, история ремонта."
    )
    pdf.h3("«Как защищены данные?»")
    pdf.body(
        "Сессия пользователя, роли, правила доступа в базе. "
        "Клиент видит свои заказы, мастер — свои, админ — панель модерации."
    )

    # 10. One sentence summary
    pdf.h2("10. Одна фраза на закрытие")
    pdf.note(
        "RepairLink — это сервис бытового ремонта «как такси»: быстрый мэтчинг мастера, "
        "фиксированная цена, безопасная сделка с комиссией только после подтверждения работы, "
        "цифровая гарантия и долгосрочный паспорт ремонта квартиры."
    )

    pdf.output(str(OUT))
    print(OUT)


if __name__ == "__main__":
    build()
